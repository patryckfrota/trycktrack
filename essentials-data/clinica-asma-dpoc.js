<div class="ess-box ess-note"><div class="ess-box-tt">Doença Pulmonar Obstrutiva Crônica</div>Doença com <i>sintomas <b>persistentes</b></i> e <i>limitação ao fluxo aéreo</i>, devido a alterações nas vias aéreas causadas por exposições significativas a partículas e gases nocivos.</div>

