<div class="ess-col ess-gray"><h4>Radical – mastectomia</h4>
<p>&gt; 20% da mama ou lesão multicêntrica</p>
<details class="ess-tg ess-gray" open><summary>Simples</summary><ul><li>Sem esvaziamento axilar</li></ul></details>
<details class="ess-tg ess-gray" open><summary>Halsted (muito pouco utilizado)</summary><ul><li>Tira o peitoral maior e menor</li><li>Tira mama e pele</li></ul></details>
<details class="ess-tg ess-gray" open><summary>Patey</summary><ul><li>Tira o peitoral menor</li></ul></details>
<details class="ess-tg ess-gray" open><summary>Madden</summary><ul><li>Não tira nenhum peitoral</li></ul></details></div>
