<p>Bizu para fixar os valores diagnósticos do TOTG para o DMG, pois esse conceito despenca em provas!</p>
<ul>
<li><b>92</b> → 9 x 2 = <b>18</b>: se multiplicarmos os dois números que compõem o 92, encontraremos o número 18 (os dois primeiros algarismos do próximo limiar) → <b>180</b></li>
